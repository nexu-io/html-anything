/** Both renderers consume the same source; no Studio palette is maintained separately. */
export function renderDesignTokens(tokens) {
  const declarations = (values, indent = '  ', prefix = 'motion-') => Object.entries(values)
    .map(([name, value]) => `${indent}--${prefix}${name}: ${value};`).join('\n');
  const header = '/* Generated by npm run design:tokens. Edit packages/design-system/tokens.json. */';
  return {
    'tokens.css': `${header}
:where([data-motion-ui]) {
${declarations(tokens.shared)}
}
:where([data-motion-ui]) {
  color-scheme: light;
${declarations(tokens.themes.light)}
}
:where([data-motion-ui][data-theme="dark"], [data-motion-ui][data-motion-studio]:not([data-theme="paper"])) {
  color-scheme: dark;
${declarations(tokens.themes.dark)}
}
@media (prefers-color-scheme: dark) {
  :where([data-motion-ui]:not([data-theme]):not([data-motion-studio])) {
    color-scheme: dark;
${declarations(tokens.themes.dark, '    ')}
  }
}
`,
    'studio/tokens.css': `${header}\n@theme static {\n${declarations(tokens.studio, '  ', '')}\n}\n`,
  };
}

